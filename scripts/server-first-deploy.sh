#!/usr/bin/env bash
# First-time install of bkh-wait on 10.10.10.159 (run ONCE, as bkhadmin, in an
# interactive ssh session — sudo will ask for the password):
#
#   ssh bkhadmin@10.10.10.159
#   git clone -q git@github-bkh-wait:bangrakamhospital/bkh-wait.git /tmp/bkh-wait-tmp
#   bash /tmp/bkh-wait-tmp/scripts/server-first-deploy.sh
#
# Prerequisite (already done): deploy key ~/.ssh/bkh_wait_deploy + ssh alias
# "github-bkh-wait" in ~/.ssh/config.
#
# Result: https://10.10.10.159:84/ (nginx :84 ssl -> pm2 bkh-wait 127.0.0.1:3084),
# PostgreSQL db bkh_wait, one staff login whose password is printed ONCE.
set -euo pipefail

APP_DIR=/var/www/wait
KPI_ENV=/var/www/kpi/.env
STAFF_USER="${STAFF_USER:-staff}"

echo "==> 1/8 app dir + clone"
sudo mkdir -p "$APP_DIR"
sudo chown bkhadmin:bkhadmin "$APP_DIR"
if [ ! -d "$APP_DIR/.git" ]; then
  git clone -q git@github-bkh-wait:bangrakamhospital/bkh-wait.git "$APP_DIR"
fi
cd "$APP_DIR"
git fetch -q origin main && git reset -q --hard origin/main
rm -rf /tmp/bkh-wait-tmp

echo "==> 2/8 .env (HIS_* copied from bkh-kpi, secrets generated)"
umask 077
if [ ! -f .env ]; then
  rnd() { openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | head -c "$1"; }
  {
    echo "# bkh-wait production env (generated by scripts/server-first-deploy.sh)"
    grep -E '^HIS_(HOST|PORT|USER|PASSWORD|DATABASE)=' "$KPI_ENV"
    echo "WAIT_DATABASE_URL="
    echo "WAIT_MIGRATE_DATABASE_URL="
    echo "WAIT_SESSION_SECRET=$(rnd 48)"
    echo "WAIT_SNAPSHOT_TOKEN=$(rnd 40)"
    echo "WAIT_INTERNAL_URL=http://127.0.0.1:3084"
  } > .env
  chmod 600 .env
  STAFF_PW="$(rnd 14)"
  ENTRY="$(printf '%s' "$STAFF_PW" | node scripts/hash-password.mjs "$STAFF_USER" staff)"
  echo "WAIT_USERS=$ENTRY" >> .env
  echo
  echo "    *** staff login (shown once, write it down) ***"
  echo "    username: $STAFF_USER"
  echo "    password: $STAFF_PW"
  echo
  unset STAFF_PW ENTRY
else
  echo "    .env exists - kept as is"
fi

echo "==> 3/8 npm packages (needed by the migration script)"
npm ci --no-audit --no-fund

echo "==> 4/8 PostgreSQL bkh_wait (roles, database, migrations)"
if grep -Eq '^WAIT_DATABASE_URL=.+' .env; then
  echo "    already configured - running migrations only"
else
  bash scripts/db-setup.sh
fi

echo "==> 5/8 build"
npm ci --no-audit --no-fund
npm run build
node --env-file=.env scripts/db-migrate.mjs

echo "==> 6/8 pm2"
if pm2 describe bkh-wait >/dev/null 2>&1; then
  pm2 restart bkh-wait --update-env
else
  pm2 start npm --name bkh-wait --cwd "$APP_DIR" -- start
fi
pm2 save

echo "==> 7/8 nginx :84 (https, same certificate as bkh-kpi :82)"
sudo tee /etc/nginx/sites-available/bkh-wait >/dev/null <<'NGINX'
server {
    listen 84 ssl;
    listen [::]:84 ssl;
    http2 on;
    server_name _;

    ssl_certificate     /etc/nginx/ssl/bkh-insight.crt;
    ssl_certificate_key /etc/nginx/ssl/bkh-insight.key;

    # plain http://host:84 -> https://host:84
    error_page 497 =301 https://$host:$server_port$request_uri;

    location / {
        proxy_pass http://127.0.0.1:3084;
        proxy_http_version 1.1;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection "upgrade";
        proxy_set_header Host $host:$server_port;
        proxy_set_header X-Forwarded-Host $host:$server_port;
        proxy_set_header X-Forwarded-Proto https;
        proxy_set_header X-Real-IP $remote_addr;
        # rate limit uses the first X-Forwarded-For entry; never pass client values
        proxy_set_header X-Forwarded-For $remote_addr;
    }
}
NGINX
sudo ln -sf /etc/nginx/sites-available/bkh-wait /etc/nginx/sites-enabled/bkh-wait
sudo nginx -t
sudo systemctl reload nginx
if sudo ufw status 2>/dev/null | grep -q "Status: active"; then
  sudo ufw allow 84/tcp
fi

echo "==> 8/8 cron: occupancy snapshot every 15 min"
mkdir -p "$APP_DIR/logs"
CRON="*/15 * * * * cd $APP_DIR && /usr/bin/node --env-file=.env scripts/snapshot.mjs >> $APP_DIR/logs/snapshot.log 2>&1"
( { crontab -l 2>/dev/null || true; } | { grep -v "/var/www/wait" || true; } ; echo "$CRON" ) | crontab -

sleep 3
echo
echo "==> check"
curl -sk -o /dev/null -w "    https://127.0.0.1:84/ -> %{http_code}\n" https://127.0.0.1:84/
curl -sk https://127.0.0.1:84/api/board | head -c 200; echo
echo "Done: https://10.10.10.159:84/"
